export const FONT_HEIGHT = 7;
const SPACE = 3;
const GAP = 1;

function glyph(ch) {
  return G[ch] ?? G[ch.toUpperCase()] ?? G['?'];
}

function advance(ch) {
  return ch === ' ' ? SPACE : glyph(ch)[0].length + GAP;
}

export function textWidth(str) {
  let w = 0;
  for (const ch of str) w += advance(ch);
  return Math.max(0, w - (str.length && str.at(-1) !== ' ' ? GAP : 0));
}

function raw(ctx, str, x, y, fill) {
  ctx.fillStyle = fill;
  let cx = Math.round(x);
  const cy = Math.round(y);
  for (const ch of str) {
    if (ch !== ' ') {
      const rows = glyph(ch);
      for (let r = 0; r < rows.length; r++) {
        for (let c = 0; c < rows[r].length; c++) if (rows[r][c] === '#') ctx.fillRect(cx + c, cy + r, 1, 1);
      }
    }
    cx += advance(ch);
  }
}

export function drawText(ctx, str, x, y, { color = PALETTE.uiText, shadow = PALETTE.shadow, align = 'left' } = {}) {
  let sx = x;
  if (align === 'center') sx = x - Math.floor(textWidth(str) / 2);
  else if (align === 'right') sx = x - textWidth(str);
  if (shadow) raw(ctx, str, sx + 1, y + 1, shadow);
  raw(ctx, str, sx, y, color);
}

// Framed panel: dark fill, 1px frame with a bright top-left bevel, cut corners, outer outline.
export function drawPanel(ctx, x, y, w, h) {
  ctx.fillStyle = PALETTE.outline;
  ctx.fillRect(x + 2, y, w - 4, h);
  ctx.fillRect(x, y + 2, w, h - 4);
  ctx.fillRect(x + 1, y + 1, w - 2, h - 2);
  ctx.fillStyle = PALETTE.uiFrame;
  ctx.fillRect(x + 2, y + 1, w - 4, h - 2);
  ctx.fillRect(x + 1, y + 2, w - 2, h - 4);
  ctx.fillStyle = PALETTE.uiBg;
  ctx.fillRect(x + 2, y + 2, w - 4, h - 4);
  ctx.fillStyle = PALETTE.uiBg2;
  ctx.fillRect(x + 3, y + 3, w - 6, 1);
  ctx.fillStyle = PALETTE.uiFrameHi;
  ctx.fillRect(x + 2, y + 1, w - 4, 1);
  ctx.fillRect(x + 1, y + 2, 1, 2);
}
